#ifndef SCI_H_
#define SCI_H_

#include "DSP2833x_Device.h"
#include "DSP2833x_Examples.h"

/* ============================================================
 * VOFA+ JustFloat 固定帧尾
 * ============================================================ */
#define JUSTFLOAT_TAIL1    0x00U
#define JUSTFLOAT_TAIL2    0x00U
#define JUSTFLOAT_TAIL3    0x80U
#define JUSTFLOAT_TAIL4    0x7FU

/* ============================================================
 * 环形缓冲区大小
 * 建议用 2 的幂，便于位运算取模
 * 这里用 1024，实际可用容量为 1023 字节
 * ============================================================ */
#define SCI_TX_BUF_SIZE    1024U
#define SCI_TX_BUF_MASK    (SCI_TX_BUF_SIZE - 1U)

/* ============================================================
 * LSPCLK 频率
 * 如果你的系统时钟没改过，F28335 常见为 37.5MHz
 * ============================================================ */
#define SCI_LSPCLK_HZ      37500000UL

/* ============================================================
 * SCI-A 初始化
 * ============================================================ */
void SCI_Init(Uint32 baud);

/* ============================================================
 * JustFloat 入队函数
 * 作用：把 data_arr[] 按 JustFloat 协议打包进环形缓冲区
 *
 * 返回：
 *   1 = 成功
 *   0 = 缓冲区空间不足，本帧丢弃
 * ============================================================ */
Uint16 SendFloatArray_JustFloat(const float32 *data_arr, Uint16 col_num);

/* ============================================================
 * 主循环里反复调用
 * 作用：把环形缓冲区里的数据灌入 SCI TX FIFO
 * ============================================================ */
void SCI_ServiceTx(void);

/* ============================================================
 * 可选：查看缓冲区溢出计数
 * ============================================================ */
Uint16 SCI_GetOverflowCount(void);

#endif